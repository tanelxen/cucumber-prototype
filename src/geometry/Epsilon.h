//  Единая политика допусков для геометрии. Все константы в юнитах уровня.
//  Геометрия считается в double: координаты карты бывают порядка тысяч, и float даёт ошибку ~1e-4,
//  сопоставимую с допусками.
//

#pragma once

namespace Geo
{
    constexpr double kOnPlane = 0.005;          // точка на таком расстоянии от плоскости считается лежащей на ней
    constexpr double kWeld = 0.01;              // вершины ближе этого расстояния сливаются в одну
    constexpr double kMinArea = 1e-3;           // грань меньшей площади вырождена
    constexpr double kPlanarity = 0.01;         // допустимое отклонение вершин грани от её плоскости
    constexpr double kWorldExtent = 131072.0;   // полуразмер базового полигона плоскости (больше любого уровня)
}
